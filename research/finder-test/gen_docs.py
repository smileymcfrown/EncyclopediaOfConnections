"""Generate Mermaid diagrams and the full path table from tree.py. Run: python3 gen_docs.py OUTDIR"""
import json, sys, os, re
sys_argv=sys.argv[:]; sys.argv=['x']
from tree import *
from tree import RESULTS
for e in E:
    d=json.load(open(RESULTS+e['file']))
    e['materials_raw']=d['finder_attributes']['materials']
OUT=sys_argv[1] if len(sys_argv)>1 else '.'
def short(n): return re.sub(r'\s*\(.*$','',n)
def esc(s): return s.replace('"',"'")
ids=iter(range(10000))
def mm(node,S,lines,depth,maxdepth,parent=None,label=None):
    q,answers=node
    qid=f"q{next(ids)}"
    lines.append(f'  {qid}{{"{esc(q)}"}}')
    if parent: lines.append(f'  {parent} --> {qid}')
    for lab,pred,child in answers:
        T=[e for e in S if pred(e)]
        aid=f"a{next(ids)}"
        leaf = not is_q(child)
        shape=('(["','"])') if leaf else ('["','"]')
        lines.append(f'  {aid}{shape[0]}{esc(lab)} · {len(T)}{shape[1]}')
        lines.append(f'  {qid} --> {aid}')
        if leaf: lines.append(f'  class {aid} leaf')
        if not leaf:
            if depth+1<maxdepth: mm(child,T,lines,depth+1,maxdepth,parent=aid)
            else: lines.append(f'  class {aid} more')
    return lines
def diagram(node,S,maxdepth):
    l=['```mermaid','flowchart LR']; mm(node,S,l,0,maxdepth)
    l+=['  classDef leaf fill:#e6f4ea,stroke:#2e7d32','  classDef more fill:#fff4e5,stroke:#b26a00','```']
    return '\n'.join(l)
md=[]
md.append('### Overview: first two questions\n')
md.append(diagram(TREE,E,2))
q,answers=TREE
for i,(lab,pred,child) in enumerate(answers,1):
    S=[e for e in E if pred(e)]
    md.append(f'\n### Branch {i}: {lab} ({len(S)} entries)\n')
    if not is_q(child):
        md.append('This answer goes straight to a shortlist; no further question.\n'); continue
    md.append(diagram(child,S,5))
open(os.path.join(OUT,'mermaid.md'),'w').write('\n'.join(md))
# path table
out=[]; walk(TREE,E,[],out)
rows=['# Every finder path and its shortlist','',
 'Generated by `gen_docs.py` from `tree.py`. ⚑ after an entry means it is on that path because of a finder tag',
 'that **needs confirming** (`research/finder-tags/tags.yaml`); the reasons are listed under the table. Most',
 'answers still use the rough rules in `tags.py` (worked out from entry names), which nobody has confirmed',
 'either; they move over to the finder tags when the finder is built (Phase 2). See `research/needs-confirming.md`.','',
 '| # | Path (answers given) | Shortlist size | Entries (outline number and name) |','|---|---|---|---|']
notes=[]
for i,(p,T,fl,tk) in enumerate(out,1):
    names='; '.join(f"{e['num']} {short(e['name'])}" + (' ⚑' if e['num'] in fl else '') for e in sorted(T, key=lambda e: e['num']))
    rows.append(f"| {i} | {' → '.join(p)}{' (then tick: '+tk.prompt.lower()+')' if tk else ''} | {len(T)} | {names} |")
    for e in sorted(T, key=lambda e: e['num']):
        for f in sorted(fl.get(e['num'], ())):
            notes.append(f"- Path {i}, ⚑ **{e['num']} {short(e['name'])}**, `{f}`: {e['nc'][f]['reason']}")
rows+=['','## Why entries are marked ⚑','']+(notes or ['None.'])
open(os.path.join(OUT,'paths.md'),'w').write('\n'.join(rows)+'\n')
# every question with its answers, examples and explanations (for review; examples.yaml)
from tree import load_examples
EXA=load_examples()
lines=['# Finder answers with examples','',
 'Every question of the draft finder, with a real-world example for each answer and, where the',
 'wording could mislead, a one-line explanation. Generated by `gen_docs.py` from `tree.py` and',
 '`examples.yaml`. In the site, the example sits next to the answer, or behind an (i) icon with a',
 'pop-up where space is short. The number after each answer is how many entries it leaves.','',
 '**Needs confirming:** Claude drafted these examples on 2026-10-06, and the owner accepted them as working text',
 'without a line-by-line review (R25). Corrections are welcome (`research/needs-confirming.md`).','']
def qa(node,S,path,depth):
    q,answers=node
    where=' → '.join(path) if path else 'Start'
    lines.append(f"{'#'*min(depth+2,6)} {q}")
    lines.append(f'*After: {where}*' if path else '*First question*')
    lines.append('')
    lines.append('| Answer | Entries | Example | Explanation |')
    lines.append('|---|---|---|---|')
    kids=[]
    for lab,pred,child in answers:
        T=[e for e in S if pred(e)]
        x=EXA.get(tuple(path)+(lab,),{})
        lines.append(f"| {lab} | {len(T)} | {x.get('example','**missing**')} | {x.get('explain','')} |")
        if is_q(child): kids.append((child,T,path+[lab]))
    lines.append('')
    for child,T,p in kids: qa(child,T,p,depth+1)
qa(TREE,E,[],0)
open(os.path.join(OUT,'answers.md'),'w').write('\n'.join(lines)+'\n')
print('ok',len(out))
